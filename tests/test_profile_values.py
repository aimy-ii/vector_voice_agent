"""Филиал и формат теории попадают в анкету своей формой, а не фразой.

Разбор прогонов по легенде с матерью за сына. В поле выбранного филиала
ложилось «Нурамыше» — распознавание переврало «на Уралмаше» — и «Метро
Проспект Космонавтов»: ориентир вместо адреса. В формате теории — «Дома»,
«Очно дома», «В теории лучше очно дома отвлекается».

Из анкеты работают дальше, а не читают её глазами: свободный текст в
таких полях хуже пустоты.
"""

from __future__ import annotations

import pytest

from graph.profile_agent import ProfileGuess, ProfileValue, guess_profile
from graph.profile_values import branch_address
from script.field_choices import load_field_choices, match_choice

#: Варианты формата теории так, как их задаёт файл данных скрипта.
THEORY = load_field_choices()["theory_format"]


class FakeAgent:
    """Агент профиля, отдающий заранее заданное."""

    def __init__(self, values: list[tuple[str, str]]) -> None:
        self._values = values

    async def guess(self, *_args, **_kwargs) -> ProfileGuess:
        """Возвращает заготовленные поля."""
        return ProfileGuess(values=[ProfileValue(key=k, value=v) for k, v in self._values])


@pytest.mark.parametrize(
    ("spoken", "expected"),
    [
        ("Теорию хочет— очно", "Очно"),
        ("очно", "Очно"),
        ("в классе", "Очно"),
        ("Дома", "Дистанционно"),
        ("дистанционно", "Дистанционно"),
        ("онлайн, в приложении", "Дистанционно"),
        ("комбинированно", "Комбинированно"),
        ("и так и так", "Комбинированно"),
    ],
)
def test_формат_теории_сводится_к_варианту(spoken: str, expected: str) -> None:
    """Сказанное приводится к одному из трёх вариантов скрипта."""
    assert match_choice(spoken, THEORY) == expected


def test_очно_дома_это_очно() -> None:
    """«Очно дома» — про очные занятия рядом с домом, а не про удалёнку.

    Порядок проверки в этом и состоит: «дома» без «очно» значит
    дистанционно, а вместе с ним — очно.
    """
    assert match_choice("Очно дома", THEORY) == "Очно"
    assert match_choice("В теории лучше очно дома отвлекается", THEORY) == "Очно"
    assert match_choice("Дома", THEORY) == "Дистанционно"


def test_неузнанный_формат_отбрасывается() -> None:
    """Ничего не узнали — поле остаётся пустым, а не мусорным."""
    assert match_choice("не знаю пока", THEORY) == ""
    assert match_choice("", THEORY) == ""


@pytest.mark.parametrize(
    "spoken",
    ["Улица Восстания, дом 21", "Коломяжский проспект, 15, корпус 2", "Кузнецова 9к2"],
)
def test_адрес_филиала_принимается(spoken: str) -> None:
    """Без карточек под рукой примета одна: номер дома."""
    assert branch_address(spoken) == spoken


#: Филиалы Екатеринбурга так, как их отдаёт справочник.
CARDS = (
    "улица Восстания, дом 21",
    "улица Кузнецова, дом 9, корпус 2",
    "улица Сулимова, дом 50",
)


@pytest.mark.parametrize(
    ("spoken", "expected"),
    [
        ("Восстание 21", "улица Восстания, дом 21"),
        ("Улица Восстания, дом 21", "улица Восстания, дом 21"),
        ("Кузнецова 9к2", "улица Кузнецова, дом 9, корпус 2"),
        ("Сулимова", "улица Сулимова, дом 50"),
    ],
)
def test_филиал_пишется_адресом_справочника(spoken: str, expected: str) -> None:
    """В анкете филиал выглядит одинаково от звонка к звонку.

    Клиент говорит «Восстание двадцать один», справочник знает «улица
    Восстания, дом 21» — это одно место, и записывать его надо одной
    записью, иначе поля не сравнить между звонками.
    """
    assert branch_address(spoken, CARDS) == expected


def test_знакомая_улица_с_чужим_номером_не_записывается() -> None:
    """Номер дома переврали: своего филиала по такому адресу нет."""
    assert branch_address("Восстания 33", CARDS) == ""


def test_ориентир_при_известных_карточках_отбрасывается() -> None:
    """Ни одна карточка не подошла, номера дома нет — это не филиал."""
    assert branch_address("Нурамыше", CARDS) == ""
    assert branch_address("Метро Проспект Космонавотов", CARDS) == ""


@pytest.mark.parametrize(
    "spoken",
    ["Нурамыше", "Метро Проспект Космонавотов", "Приморский район", "", "   "],
)
def test_ориентир_филиалом_не_считается(spoken: str) -> None:
    """По ориентиру филиал ещё только подбирают, и он лежит в своём поле."""
    assert branch_address(spoken) == ""


async def test_агент_профиля_чистит_оба_поля() -> None:
    """Мусор до анкеты не доходит, годное доходит."""
    guess = await guess_profile(
        "на Уралмаше, теорию очно",
        known={},
        fields=[("branch", "Филиал"), ("theory_format", "Формат"), ("city", "Город")],
        agent=FakeAgent(
            [
                ("branch", "Нурамыше"),
                ("theory_format", "Теорию хочет— очно"),
                ("city", "Екатеринбург"),
            ]
        ),
    )

    assert [(v.key, v.value) for v in guess.values] == [
        ("theory_format", "Очно"),
        ("city", "Екатеринбург"),
    ]


def test_варианты_лежат_в_данных_а_не_в_коде() -> None:
    """Заказчик правит варианты в файле рядом со скриптом, без выката кода.

    Форматы теории названы в требованиях шага прозой — «очно,
    дистанционно или комбинированно», — а технических полей в ``SalesStep``
    нет намеренно. Поэтому перечень лежит отдельным файлом данных, как
    перечень возражений.
    """
    from script.field_choices import DEFAULT_FILE

    assert DEFAULT_FILE.exists()
    values = {choice.value for choice in THEORY}
    assert values == {"Очно", "Дистанционно", "Комбинированно"}


def test_без_файла_значение_идёт_в_анкету_как_есть(tmp_path) -> None:
    """Отсутствие перечня не ломает разбор — оно лишь снимает сведение."""
    from script.field_choices import load_field_choices as load

    assert load(tmp_path / "нет-такого.json") == {}
