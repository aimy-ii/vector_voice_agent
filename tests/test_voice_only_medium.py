"""Собеседник на телефоне: он говорит, а не пишет.

Проблема из разбора: на шаге обмена контактами бот просил написать,
отправить или заполнить. В правилах речи про телефон сказано трижды, но
каждый раз про речь самого агента — как ему формулировать. Что собеседник
тоже только говорит и не может ничего нажать, не было сказано нигде, и
модель зеркалила письменную тему шага на человека.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from graph.prompts import SPOKEN_INTRO

#: Каталог версий скрипта.
DATA = Path(__file__).resolve().parents[1] / "src" / "script" / "data"

#: Просьбы к собеседнику, которых в телефонном разговоре быть не может.
WRITTEN = re.compile(
    r"\b(напишите|отправьте|пришлите|скиньте|заполните|нажмите|введите)\b",
    re.IGNORECASE,
)


def test_правило_про_собеседника_есть_в_первом_же_блоке():
    """Правило живёт в SPOKEN_INTRO: его модель читает первым."""
    lowered = SPOKEN_INTRO.lower()
    assert "собеседник тоже только говорит" in lowered
    assert "клавиатура" in lowered


@pytest.mark.parametrize("verb", ["написать", "отправить", "заполнить", "нажать"])
def test_запрещённые_просьбы_перечислены_поимённо(verb: str):
    """Общего «только голосом» мало: модель нужно ткнуть в конкретные слова."""
    assert verb in SPOKEN_INTRO.lower()


def test_свои_действия_агенту_разрешены():
    """«Напишу вам в мессенджер» — действие агента, а не просьба к человеку.

    Без этой оговорки правило вычистило бы и обмен контактами: бот
    перестал бы обещать написать, а это цель шага.
    """
    assert "напишу вам в мессенджер" in SPOKEN_INTRO.lower()


def test_в_скрипте_нет_просьб_писать():
    """Образцы шагов не учат бота просить заполнить анкету.

    Модель строит фразу от образца. Пока в примере шага «Закрытие» стояло
    «Отправлю анкету. Заполните», никакое правило речи не помогало.
    """
    script = json.loads((DATA / "vector_ru.v4.json").read_text(encoding="utf-8"))
    offenders = [
        (step["id"], example)
        for step in script["steps"]
        for example in step.get("examples", [])
        if WRITTEN.search(example)
    ]
    assert offenders == []
