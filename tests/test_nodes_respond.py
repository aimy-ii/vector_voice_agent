async def test_после_секундочки_бот_берёт_ход_сам(monkeypatch) -> None:
    """Модель не успела — человека не просят повторить, а договаривают.

    Клиент сказал, ответа не дождались за отведённое время. Раньше бот
    отвечал «Прошу прощения, отвлеклась на секунду. Повторите,
    пожалуйста?» — человека услышали, повторять ему нечего, и просьба
    выглядит нелепо. Теперь бот говорит «Секундочку» и сам берёт
    следующий ход; от бесконечной цепочки оберегает предел продолжений на
    стороне бота.
    """
    from core.config import settings

    assert settings.agent_fallback == "Секундочку, пожалуйста."
    assert "повтор" not in settings.agent_fallback.lower()


def test_ожидание_ответа_модели_не_короче_десяти_секунд() -> None:
    """На промпте в двадцать тысяч знаков восьми секунд не хватало.

    С таймаутом в восемь секунд модель не укладывалась дважды за
    шестнадцать ходов, и вместо ответа звучала аварийная реплика.
    Проверяем значение по умолчанию: на стенде оно приходит из окружения,
    и подменять его окружением можно, а ронять ниже — нет.
    """
    from core.config import Settings

    assert Settings.model_fields["llm_read_timeout"].default >= 10.0
