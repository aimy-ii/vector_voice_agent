def build_filler_messages(
    script: CompiledScript,
    *,
    messages: Sequence[BaseMessage],
    history_limit: int,
) -> list[BaseMessage]:
    """Собирает запрос на короткий отклик-заглушку, пока фон добывает данные.

    Не реплика, а знак «услышал» и пауза перед ответом. Промпт короткий —
    отклик должен родиться быстрее всего.

    Args:
        script: скомпилированный скрипт (нужна только персона).
        messages: история разговора.
        history_limit: сколько последних сообщений оставить.

    Returns:
        Список сообщений: одно системное и короткий хвост истории.
    """
    _ = script
    system = (
        f"{settings.agent_name}, к клиенту на «Вы», живой тон. "
        "Короткий отклик — не реплика: знак, что услышал, и взять паузу перед ответом. "
        "Ограничение длины: два-три слова, максимум одно короткое предложение. "
        "Не оценивать сказанное — никаких «замечательный выбор», "
        "«звучит основательно», «отличный город». "
        "Не рассуждать и не расспрашивать о чувствах, впечатлениях и ощущениях. "
        f"{_STUB_NO_QUESTION} "
        "Не сообщать фактов. "
        "Не повторять то, что уже говорил в этом разговоре. "
        f"{_SPOKEN_ONLY_SHORT} "
        f"{_HARD_FACT_BAN}"
    )
    limit = max(1, int(history_limit))
    tail = list(messages)[-limit:]
    if not tail:
        tail = [HumanMessage(content="(клиент молчит)")]
    return [SystemMessage(content=system), *tail]


def build_waiting_messages(
    script: CompiledScript,
    *,
    messages: Sequence[BaseMessage],
    profile: Mapping[str, str],
    pending_fields: Sequence[str],
    step: AnyStep | None,
    history_limit: int,
    turn_kind: str = "client",
    context_text: str = "",
) -> list[BaseMessage]:
    """Собирает укороченный запрос к генератору для реплики ожидания.

    Реплика короткая и нужна быстро, поэтому в промпт не идут факты
    и шапка шагов: только правила речи, уже добытый контекст, ведущий
    шаг одной строкой, что уточняется, и хвост диалога.

    Args:
        script: скомпилированный скрипт.
        messages: история разговора.
        profile: профиль клиента.
        pending_fields: поля, которые сейчас разбираются.
        step: ведущий шаг, чтобы не терять нить.
        history_limit: сколько последних сообщений оставить.
        turn_kind: ``client`` или ``continuation``.
        context_text: уже добытый контекст (статика и динамика).

    Returns:
        Список сообщений: одно системное и обрезанный хвост истории.
    """
    lines = [
        f"Роль: {settings.agent_name}, {settings.agent_role} «{settings.agent_company}».",
        "К клиенту только на «Вы». Тон живой, без канцелярита.",
        "Реплика ожидания — одно короткое предложение, не длиннее восьми слов.",
        "Никаких объяснений, зачем уточняешь, и никаких хвостов вроде "
        "«чтобы было удобно», «чтобы всё было понятно», «максимально точно» — "
        "они канцелярские и в живой речи не встречаются. "
        "Запрещены придаточные цели и обороты про удобство клиента.",
        "Задача: сказать своими словами, что сейчас готовишь, и удержать "
        "разговор. Предмет назвать конкретно: из хвоста диалога и из "
        "текущего шага пойми, что именно готовится, и скажи это своими "
        "словами — лучше «сейчас подберу …», чем голое «сейчас уточню "
        "информацию».",
        "Не выдумывать данные, не называть цифры и адреса, не начинать заново, не здороваться.",
        _HARD_FACT_BAN,
        _STUB_NO_QUESTION,
        _SPOKEN_ONLY_SHORT,
        "Реплика опирается на историю разговора. Не повторять сказанное.",
    ]
    cont = continuation_block(turn_kind=turn_kind)
    if cont:
        lines.append(cont)
    ctx = context_block(context_text)
    if ctx:
        lines.append(ctx)
    if step is not None:
        name = getattr(step, "name", None) or getattr(step, "goal", None) or step.id
        lines.append(f"Ведущий шаг: {step.id} — {name}.")
    form = profile_block(script, profile, pending_fields=pending_fields)
    lines.append(form)

    limit = max(1, int(history_limit))
    tail = list(messages)[-limit:]
    if not tail:
        tail = [HumanMessage(content="(клиент молчит)")]
    return [SystemMessage(content="\n".join(lines)), *tail]


def _pull_head(
    *,
    steps: Sequence[AnyStep] | None,
    step: AnyStep | None,
) -> list[AnyStep]:
    """Собирает шапку хода вытаскивания так же, как полная сборка.

    Args:
        steps: шаги в работе; первый — ведущий. ``None`` — взять ``step``.
        step: ведущий шаг для совместимости, если ``steps`` не передали.

    Returns:
        Шаги шапки; пустой список, если шага нет.
    """
    if steps is not None:
        return list(steps)
    if step is not None:
        return [step]
    return []


def _pull_steps_block(
    steps: Sequence[AnyStep],
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    *,
    context_text: str = "",
) -> str:
    """Собирает шапку шагов для короткой сборки вытаскивания.

    Ведущий (первый) выделен как основной, остальные — как незакрытые
    темы. Требования на месте, примеры и правила полной сборки — нет:
    шапка здесь меню тем к рассуждению, а не текст реплики.

    Args:
        steps: шаги в работе; первый — ведущий.
        profile: профиль для ветвления текста.
        facts: факты хода для подстановки.
        context_text: документ контекста для проверки ``knowledge``.

    Returns:
        Текст шапки; если шагов нет — ``_PULL_STEPS_NONE``.
    """
    if not steps:
        return _PULL_STEPS_NONE
    guard_id = _guard_step_id(steps, context_text=context_text, facts=facts)
    parts = [
        _PULL_STEPS_INTRO,
        "",
        "Основной:",
        next_step_block(
            steps[0],
            profile,
            facts,
            context_text=context_text,
            with_guard=steps[0].id == guard_id,
        ),
    ]
    if len(steps) > 1:
        hang = "\n\n".join(
            next_step_block(
                item,
                profile,
                facts,
                context_text=context_text,
                with_guard=item.id == guard_id,
            )
            for item in steps[1:]
        )
        parts.extend(["", "Незакрытые темы:", hang])
    return "\n".join(parts)


def build_pull_messages(
    script: CompiledScript,
    *,
    messages: Sequence[BaseMessage],
    profile: Mapping[str, str],
    pending_fields: Sequence[str] = (),
    step: AnyStep | None = None,
    steps: Sequence[AnyStep] | None = None,
    facts: Mapping[str, Any] | None = None,
    context_text: str = "",
    interrupted_reply: str = "",
    closed_steps: Sequence[AnyStep] = (),
    next_step: AnyStep | None = None,
) -> list[BaseMessage]:
    """Собирает укороченный запрос к генератору для хода вытаскивания.

    Ход включается, когда предыдущая реплика бота вопроса не содержала и
    человек после неё молчит. Нужна следующая реплика разговора, а не полный
    ход продажи, поэтому в промпт идут роль, порядок мышления, требования к
    готовой реплике, шапка шагов в работе, закрытые шаги, следующий шаг,
    контекст и форма разговора. Полного перечня правил речи и сводки
    сценария нет.

    Шапка, закрытые и следующий шаг приходят тем же путём, что в полную
    сборку: без них модели не из чего брать тему, и она продолжает
    последнюю собственную реплику. Ведущий в шапке выделен как основной,
    остальные — как незакрытые темы. Следующий шаг — ориентир, не задание.

    Промпт построен вокруг последовательности действий: прочитать разговор,
    найти, на чём он повис, продолжить с последней своей реплики, сказать
    новое с вопросом. Запрет повтора — отдельное требование к готовой
    реплике, рядом с вопросом.

    История разговора уходит целиком, как в полной сборке: на ней держится
    первый шаг рассуждения — по хвосту из нескольких сообщений не видно, что
    уже сказано и обещано. Исключение — услышанный кусок прерванной реплики:
    он уходит в раздел обрыва, а не второй раз хвостом истории и не в раздел
    последней реплики.

    Args:
        script: скомпилированный скрипт (нужен для формы разговора).
        messages: история разговора; уходит целиком.
        profile: собранный профиль.
        pending_fields: поля, которые сейчас разбираются.
        step: ведущий шаг для совместимости, если ``steps`` не передали;
            ``None`` — шага нет.
        steps: шаги шапки; первый — ведущий. Если заданы, ``step`` не
            используется.
        facts: факты хода; в промпт не выводятся, нужны для подстановки
            в опорные формулировки шага.
        context_text: уже добытый контекст (статика и динамика).
        interrupted_reply: услышанная часть прерванной реплики бота;
            пустая строка — раздела обрыва нет.
        closed_steps: шаги, уже закрытые к этому ходу; пустой перечень —
            раздела нет.
        next_step: следующий шаг после шапки; ``None`` или шаг из шапки —
            раздела нет.

    Returns:
        Список сообщений: одно системное и полная история.
    """
    head = _pull_head(steps=steps, step=step)
    facts_map = dict(facts or {})
    lines = [
        f"Роль: {settings.agent_name}, {settings.agent_role} «{settings.agent_company}». "
        f"Тон: {settings.agent_tone}.",
        f"К клиенту только на «Вы», всегда. {_gender_speech_rule(settings.agent_gender)}",
        continuation_block(turn_kind="pull"),
        _PULL_SITUATION,
        _PULL_THINKING,
        _PULL_QUESTION,
        _PULL_NO_REPEAT,
        _HARD_FACT_BAN,
        _SPOKEN_ONLY_SHORT,
        _PULL_BOUNDS,
    ]
    tail = _history_without_interrupted_echo(messages, interrupted_reply)
    last_reply = last_agent_reply_block(tail)
    if last_reply:
        lines.insert(lines.index(_PULL_THINKING), last_reply)
    ctx = context_block(context_text)
    if ctx:
        lines.append(ctx)
    interrupted = interrupted_reply_block(interrupted_reply)
    if interrupted:
        lines.append(interrupted)
    closed = closed_steps_block(closed_steps)
    if closed:
        lines.append(closed)
    hat = _pull_steps_block(head, profile, facts_map, context_text=context_text)
    if hat:
        lines.append(hat)
    head_ids = {item.id for item in head}
    if next_step is not None and next_step.id not in head_ids:
        lines.append(f"{_PULL_NEXT_INTRO}\n{next_step_block(next_step, profile, facts_map)}")
    lines.append(profile_block(script, profile, pending_fields=pending_fields))

    if not tail:
        tail = [HumanMessage(content="(клиент молчит)")]
    return [SystemMessage(content="\n".join(lines)), *tail]


def _section(title: str, body: str) -> str | None:
    """Собирает раздел верхнего уровня; пустое тело — None."""
    text = body.strip()
    if not text:
        return None
    return f"# {title}\n{text}"


def _subsection(title: str, body: str) -> str | None:
    """Собирает подраздел; пустое тело — None."""
    text = body.strip()
    if not text:
        return None
    return f"## {title}\n{text}"


def build_turn_messages(
    *,
    script: CompiledScript,
    steps: Sequence[AnyStep] | None = None,
    step: AnyStep | None = None,
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    history: Sequence[BaseMessage],
    asides_done: Sequence[str],
    next_step: AnyStep | None = None,
    context_text: str = "",
    dynamic_status: str = "",
    pending_fields: Sequence[str] = (),
    turn_kind: str = "client",
    closed_steps: Sequence[AnyStep] = (),
    mode: TurnMode = "normal",
    interrupted_reply: str = "",
) -> list[BaseMessage]:
    """Собирает сообщения запроса к генератору.

    Системное сообщение — разделы верхнего уровня в фиксированном порядке.
    Пустой раздел не выводится. Ветка ожидания сюда не входит.

    Args:
        script: скомпилированный скрипт.
        steps: шаги в работе; первый — «СЕЙЧАС ГОВОРИМ ОБ ЭТОМ»,
            остальные — «ЕЩЁ НЕ ЗАКРЫТО»; если None — из step.
        step: текущий шаг (совместимость).
        profile: собранный профиль.
        facts: факты хода.
        history: история звонка без системных сообщений; уходит целиком,
            кроме услышанного куска прерванной реплики — он только
            в разделе обрыва.
        asides_done: отработанные возражения.
        next_step: следующий шаг; раздел «ЧТО ДАЛЬШЕ», без примеров.
        context_text: документ контекста.
        dynamic_status: статус динамики контекста (``готово`` / ``не нашлось``).
        pending_fields: поля профиля, которые сейчас разбираются.
        turn_kind: ``client`` или ``continuation``.
        closed_steps: шаги, уже закрытые к этому ходу.
        mode: режим сборки правил и раздела шага.
        interrupted_reply: услышанная часть прерванной реплики бота;
            пустая строка — раздела обрыва нет.

    Returns:
        Список сообщений: одно системное и полная история.
    """
    head: list[AnyStep]
    if steps is not None:
        head = list(steps)
    elif step is not None:
        head = [step]
    else:
        head = []

    how_parts = [persona_block()]
    cont = continuation_block(turn_kind=turn_kind)
    if cont:
        how_parts.append(cont)

    context_parts: list[str] = []
    profile_text = profile_block(script, profile, pending_fields=pending_fields)
    sub = _subsection("Что известно о собеседнике", profile_text)
    if sub:
        context_parts.append(sub)
    ctx_for_steps = ""
    if context_text:
        ctx = context_block(context_text)
        if ctx:
            sub = _subsection("Данные справочника", ctx)
            if sub:
                context_parts.append(sub)
            ctx_for_steps = context_text
    facts_text = facts_block(facts)
    if facts_text:
        sub = _subsection("Факты этого хода", facts_text)
        if sub:
            context_parts.append(sub)
    status_note = dynamic_status_block(status=dynamic_status)
    if status_note:
        sub = _subsection("Статус фона", status_note)
        if sub:
            context_parts.append(sub)
    closed = closed_steps_block(closed_steps)
    if closed:
        sub = _subsection("Уже закрыто", closed)
        if sub:
            context_parts.append(sub)

    sections: list[str] = [SPOKEN_INTRO]
    how = _section("КАК РАБОТАТЬ", "\n\n".join(how_parts))
    if how:
        sections.append(how)
    destination = _section("КУДА ВЕДЁМ РАЗГОВОР", script.summary)
    if destination:
        sections.append(destination)
    rules = _section("ПРАВИЛА РЕЧИ", speech_rules_block(mode=mode))
    if rules:
        sections.append(rules)
    if context_parts:
        ctx_section = _section("КОНТЕКСТ", "\n\n".join(context_parts))
        if ctx_section:
            sections.append(ctx_section)

    interrupted = _section("РЕПЛИКА ПРЕРВАНА", interrupted_reply_block(interrupted_reply))
    if interrupted:
        sections.append(interrupted)

    steps_text = steps_block(head, profile, facts, context_text=ctx_for_steps, mode=mode)
    if steps_text:
        sections.append(steps_text)

    head_ids = {item.id for item in head}
    if next_step is not None and next_step.id not in head_ids:
        next_text = next_step_block(next_step, profile, facts)
        next_section = _section("ЧТО ДАЛЬШЕ", next_text)
        if next_section:
            sections.append(next_section)

    form_parts = [
        "Вернуть ответ строго по схеме. В поле reply — только то, что звучит "
        "вслух: живой разговорный русский, без списков и канцелярита."
    ]
    if not script.is_sales:
        form_parts.insert(0, aside_block(script, asides_done))
    form = _section("ФОРМА ОТВЕТА", "\n\n".join(form_parts))
    if form:
        sections.append(form)

    initiative = _section("ИНИЦИАТИВА", _INITIATIVE_BLOCK)
    if initiative:
        sections.append(initiative)

    tail = _history_without_interrupted_echo(history, interrupted_reply)
    if not tail:
        tail = [HumanMessage(content="(клиент молчит)")]
    return [SystemMessage(content="\n\n".join(sections)), *tail]
