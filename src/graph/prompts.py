#: Слово короче четырёх букв смысла описания не несёт и в сравнение не идёт.
_FACT_WORD_MIN = 4

#: Хвост в два символа отбрасывается, чтобы падежи не мешали сравнению:
#: «города» и «городе» дают одну основу «горо».
_FACT_STEM_TAIL = 2


def _fact_stems(fact: str) -> list[str]:
    """Разбирает описание знания на основы значимых слов.

    Args:
        fact: описание знания из ``knowledge`` шага.

    Returns:
        Основы слов длиной от четырёх букв; пустой список, если значимых
        слов в описании нет.
    """
    words = [word for word in re.split(r"\W+", fact.lower()) if len(word) >= _FACT_WORD_MIN]
    return [
        word[:-_FACT_STEM_TAIL] if len(word) >= _FACT_WORD_MIN + _FACT_STEM_TAIL else word
        for word in words
    ]


def _context_has_fact(context_text: str, facts: Mapping[str, Any], fact: str) -> bool:
    """Есть ли знание шага в контексте хода или в фактах хода.

    Сначала ищется описание целиком. Если его нет, знание считается
    найденным только тогда, когда в контексте (или в фактах) встретились
    основы всех значимых слов описания. Совпадения пары случайных слов из
    разных тем недостаточно: иначе предохранитель о нехватке данных
    пропадает там, где данных на самом деле нет.

    Args:
        context_text: документ контекста хода.
        facts: факты хода.
        fact: описание знания из ``knowledge`` шага.

    Returns:
        ``True``, если знание считается доступным, иначе ``False``.
    """
    needle = fact.strip().lower()
    if not needle:
        return True
    haystack = (context_text or "").lower()
    if needle in haystack:
        return True
    stems = _fact_stems(needle)
    if not stems:
        return False
    if all(stem in haystack for stem in stems):
        return True
    body = json.dumps(facts, ensure_ascii=False).lower() if facts else ""
    return bool(body) and all(stem in body for stem in stems)


#: Указание при нехватке данных. Печатается один раз на всю шапку: смысл
#: у него общий, а повтор у каждого шага только разбавляет остальное.
_MISSING_KNOWLEDGE_GUARD = "Вести разговор без чисел и конкретных величин, не выдумывать."


def _missing_knowledge_line(
    step: SalesStep,
    *,
    context_text: str,
    facts: Mapping[str, Any],
    with_guard: bool = True,
) -> str | None:
    """Строка о нехватке данных из ``knowledge``, если их нет в контексте.

    Args:
        step: шаг продаж.
        context_text: документ контекста хода.
        facts: факты хода.
        with_guard: дописать ли указание не выдумывать величины. ``False`` —
            только перечисление недостающего, указание даёт другой шаг шапки.

    Returns:
        Строка о нехватке данных или ``None``, если всё нужное есть.
    """
    if not step.knowledge:
        return None
    missing = [
        fact
        for fact in step.knowledge
        if fact.strip() and not _context_has_fact(context_text, facts, fact)
    ]
    if not missing:
        return None
    joined = "; ".join(missing)
    line = f"В контексте нет данных: {joined}."
    return f"{line} {_MISSING_KNOWLEDGE_GUARD}" if with_guard else line


