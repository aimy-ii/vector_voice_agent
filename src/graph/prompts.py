def _fact_stems(fact: str) -> list[str]:
    """Разбирает описание знания на основы значимых слов.

    Args:
        fact: описание знания из ``knowledge`` шага.

    Returns:
        Основы слов длиной от четырёх букв; пустой список, если значимых
        слов в описании нет.
    """
    words = [word for word in re.split(r"\W+", fact.lower()) if len(word) >= _FACT_WORD_MIN]
    return [
        word[:-_FACT_STEM_TAIL] if len(word) >= _FACT_WORD_MIN + _FACT_STEM_TAIL else word
        for word in words
    ]


def _context_has_fact(context_text: str, facts: Mapping[str, Any], fact: str) -> bool:
    """Есть ли знание шага в контексте хода или в фактах хода.

    Сначала ищется описание целиком. Если его нет, знание считается
    найденным только тогда, когда в контексте (или в фактах) встретились
    основы всех значимых слов описания. Совпадения пары случайных слов из
    разных тем недостаточно: иначе предохранитель о нехватке данных
    пропадает там, где данных на самом деле нет.

    Args:
        context_text: документ контекста хода.
        facts: факты хода.
        fact: описание знания из ``knowledge`` шага.

    Returns:
        ``True``, если знание считается доступным, иначе ``False``.
    """
    needle = fact.strip().lower()
    if not needle:
        return True
    haystack = (context_text or "").lower()
    if needle in haystack:
        return True
    stems = _fact_stems(needle)
    if not stems:
        return False
    if all(stem in haystack for stem in stems):
        return True
    body = json.dumps(facts, ensure_ascii=False).lower() if facts else ""
    return bool(body) and all(stem in body for stem in stems)


#: Указание при нехватке данных. Печатается один раз на всю шапку: смысл
#: у него общий, а повтор у каждого шага только разбавляет остальное.
_MISSING_KNOWLEDGE_GUARD = "Вести разговор без чисел и конкретных величин, не выдумывать."


def _missing_knowledge_line(
    step: SalesStep,
    *,
    context_text: str,
    facts: Mapping[str, Any],
    with_guard: bool = True,
) -> str | None:
    """Строка о нехватке данных из ``knowledge``, если их нет в контексте.

    Args:
        step: шаг продаж.
        context_text: документ контекста хода.
        facts: факты хода.
        with_guard: дописать ли указание не выдумывать величины. ``False`` —
            только перечисление недостающего, указание даёт другой шаг шапки.

    Returns:
        Строка о нехватке данных или ``None``, если всё нужное есть.
    """
    if not step.knowledge:
        return None
    missing = [
        fact
        for fact in step.knowledge
        if fact.strip() and not _context_has_fact(context_text, facts, fact)
    ]
    if not missing:
        return None
    joined = "; ".join(missing)
    line = f"В контексте нет данных: {joined}."
    return f"{line} {_MISSING_KNOWLEDGE_GUARD}" if with_guard else line


def _describe_sales_step(
    step: SalesStep,
    *,
    context_text: str = "",
    facts: Mapping[str, Any] | None = None,
    with_guard: bool = True,
) -> list[str]:
    """Собирает строки описания шага продаж: название, требования, примеры.

    Args:
        step: шаг продаж.
        context_text: документ контекста (для проверки ``knowledge``).
        facts: факты хода.
        with_guard: дописывать ли к разделу о нехватке данных указание
            не выдумывать величины.

    Returns:
        Список строк описания.
    """
    lines = [
        f"## {step.name}",
        "",
        "**Требования**",
        step.requirements,
    ]
    if step.examples:
        lines.append("")
        lines.append("**Примеры**")
        lines.extend(step.examples)
    gap = _missing_knowledge_line(
        step,
        context_text=context_text,
        facts=facts or {},
        with_guard=with_guard,
    )
    if gap:
        lines.append("")
        lines.append("**Не хватает данных**")
        lines.append(gap)
    return lines


def _describe_step(
    step: AnyStep,
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    *,
    heading: str = "",
    context_text: str = "",
    with_guard: bool = True,
) -> list[str]:
    """Собирает строки описания одного шага для промпта.

    Args:
        step: шаг скрипта.
        profile: профиль для ветвления текста.
        facts: факты хода для подстановки.
        heading: устаревший параметр; игнорируется.
        context_text: документ контекста (для проверки ``knowledge``).
        with_guard: дописывать ли к разделу о нехватке данных указание
            не выдумывать величины.

    Returns:
        Список строк описания.
    """
    del heading
    if isinstance(step, SalesStep):
        return _describe_sales_step(
            step,
            context_text=context_text,
            facts=facts,
            with_guard=with_guard,
        )

    lines = [
        f"## {step.goal}",
        "",
        "**Требования**",
        step.goal,
    ]
    if step.why:
        lines.append(f"Зачем: {step.why}")
    text = render_step_text(step, profile)
    if text:
        filled = fill_facts(text, facts)
        if filled:
            if step.verbatim:
                lines.append(f"{_SAMPLE_PREFIX}\n{filled}")
            else:
                lines.append("Опорная формулировка (можно сказать своими словами):\n" + filled)
    if step.avoid:
        lines.append(f"На этом шаге нельзя: {step.avoid}")
    if step.check_question:
        lines.append(
            "Образец смысла проверки (обязателен в конце реплики; сформулировать "
            "своими словами, живо и коротко, не зачитывать дословно):\n"
            f"«{step.check_question}»"
        )
    if step.options:
        lines.append(
            "Предложить выбор из вариантов, а не открытый вопрос: " + ", ".join(step.options)
        )
    if step.fills:
        lines.append("Шаг собирает поля: " + ", ".join(step.fills))
    if step.examples:
        lines.append("")
        lines.append("**Примеры**")
        lines.extend(step.examples)
    return lines


def next_step_block(
    step: AnyStep,
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    *,
    context_text: str | None = None,
    with_guard: bool = True,
) -> str:
    """Описывает следующий шаг как ориентир: только название и требования.

    Args:
        step: следующий незакрытый шаг после перечня.
        profile: профиль для ветвления текста.
        facts: факты хода для подстановки.
        context_text: документ контекста для проверки ``knowledge``.
            ``None`` (по умолчанию) — прежнее поведение, без раздела
            о нехватке: так собирается ориентир «ЧТО ДАЛЬШЕ».
            Строка, в том числе пустая, — проверить knowledge и при
            отсутствии данных дописать ``**Не хватает данных**``.
        with_guard: дописывать ли к разделу о нехватке данных указание
            не выдумывать величины.

    Returns:
        Текст раздела «ЧТО ДАЛЬШЕ» без примеров; для висящего шага —
        то же плюс нехватка данных, если передан ``context_text``.
    """
    if isinstance(step, SalesStep):
        text = f"## {step.name}\n\n**Требования**\n{step.requirements}"
        if context_text is not None:
            gap = _missing_knowledge_line(
                step,
                context_text=context_text,
                facts=facts,
                with_guard=with_guard,
            )
            if gap:
                text = f"{text}\n\n**Не хватает данных**\n{gap}"
        return text

    lines = [
        f"## {step.goal}",
        "",
        "**Требования**",
        step.goal,
    ]
    if step.check_question:
        lines.append(
            f"Образец смысла вопроса (сформулировать своими словами):\n«{step.check_question}»"
        )
    text = render_step_text(step, profile)
    if text:
        filled = fill_facts(text, facts)
        if filled:
            lines.append("Опорная формулировка вопроса (можно своими словами):\n" + filled)
    if step.options:
        lines.append(
            "Предложить выбор из вариантов, а не открытый вопрос: " + ", ".join(step.options)
        )
    return "\n".join(lines)


def _guard_step_id(
    steps: Sequence[AnyStep],
    *,
    context_text: str,
    facts: Mapping[str, Any],
) -> str | None:
    """Находит шаг шапки, при котором печатается указание о нехватке данных.

    Указание общее на всю шапку, поэтому достаётся первому шагу, которому
    данных не хватает; остальным остаётся только перечень недостающего.

    Args:
        steps: шаги шапки; первый — тема реплики.
        context_text: документ контекста хода.
        facts: факты хода.

    Returns:
        Идентификатор шага или ``None``, если данных хватает всем.
    """
    for step in steps:
        if not isinstance(step, SalesStep):
            continue
        if _missing_knowledge_line(step, context_text=context_text, facts=facts):
            return step.id
    return None


def steps_block(
    steps: Sequence[AnyStep],
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    *,
    context_text: str = "",
    next_step: AnyStep | None = None,
    mode: TurnMode = "normal",
) -> str:
    """Собирает разделы текущего и незакрытых шагов.

    Первый шаг из ``steps`` — раздел «СЕЙЧАС ГОВОРИМ ОБ ЭТОМ» целиком
    (требования, примеры, нехватка данных). Остальные — «ЕЩЁ НЕ ЗАКРЫТО»
    только с названием и требованиями. ``next_step`` сюда не входит.
    При ``mode="pull"`` перед текущим разделом — «ЗАДАЧА ЭТОГО ХОДА».

    Нехватка данных отмечается у каждого шага, которому знаний не хватает,
    а указание не выдумывать величины печатается один раз — у первого
    такого шага: смысл у него общий на всю шапку.

    Вступление раздела заканчивается требованием ``_STEPS_CONVERSATION_FIRST``:
    последовательность разговора выше порядка шагов.

    Args:
        steps: шаги в работе; первый — тема реплики.
        profile: профиль.
        facts: факты хода (без перечня городов).
        context_text: документ контекста для проверки нехватки знаний.
        next_step: игнорируется; ориентир собирается отдельно.
        mode: режим сборки; ``repeat`` — врезка ``LEAD_REPEAT_INTRO``;
            ``pull`` — задача вытаскивания перед описанием шага.

    Returns:
        Текст с заголовками разделов; пустая строка, если нечего показать.
    """
    del next_step
    if not steps:
        closed = (
            "Все шаги скрипта закрыты. Отвечать на вопросы собеседника и мягко "
            "подводить разговор к завершению."
        )
        section = _section("СЕЙЧАС ГОВОРИМ ОБ ЭТОМ", closed)
        return section or ""

    parts: list[str] = []
    if mode == "pull":
        task = _section("ЗАДАЧА ЭТОГО ХОДА", PULL_TASK)
        if task:
            parts.append(task)

    guard_id = _guard_step_id(steps, context_text=context_text, facts=facts)
    intro = _STEPS_FOCUS_INTRO
    if len(steps) > 1:
        intro = f"{intro} {_STEPS_HANGING_NOTE}"
    intro = f"{intro}\n\n{_STEPS_CONVERSATION_FIRST}"
    current_body = "\n".join(
        [
            intro,
            "",
            *_describe_step(
                steps[0],
                profile,
                facts,
                context_text=context_text,
                with_guard=steps[0].id == guard_id,
            ),
        ]
    )
    if mode == "repeat" and current_body:
        current_body = f"{LEAD_REPEAT_INTRO}\n\n{current_body}"

    now = _section("СЕЙЧАС ГОВОРИМ ОБ ЭТОМ", current_body)
    if now:
        parts.append(now)

    if len(steps) > 1:
        hang_body = "\n\n".join(
            next_step_block(
                step,
                profile,
                facts,
                context_text=context_text,
                with_guard=step.id == guard_id,
            )
            for step in steps[1:]
        )
        hang = _section("ЕЩЁ НЕ ЗАКРЫТО", hang_body)
        if hang:
            parts.append(hang)

    return "\n\n".join(parts)


def step_block(
    step: AnyStep,
    profile: Mapping[str, str],
    facts: Mapping[str, Any],
    *,
    next_step: AnyStep | None = None,
    context_text: str = "",
) -> str:
    """Совместимая обёртка: шаг в работе и отдельно следующий как ориентир.

    Args:
        step: первый шаг перечня.
        profile: профиль.
        facts: факты хода.
        next_step: следующий шаг или None; ориентир дальнейшего хода.
        context_text: документ контекста.

    Returns:
        Текстовый блок: шаги в работе и при необходимости «что дальше».
    """
    body = steps_block(
        [step],
        profile,
        facts,
        context_text=context_text,
    )
    if next_step is None:
        return body
    return f"{body}\n\n{next_step_block(next_step, profile, facts)}"


def facts_block(facts: Mapping[str, Any]) -> str:
    """Выкладывает факты хода без перечня городов и полного списка филиалов.

    Args:
        facts: факты, принесённые из справочника / резолверов.

    Returns:
        Текстовый блок или пустая строка.
    """
    payload = {
        k: v
        for k, v in facts.items()
        if v not in (None, "", [], {}) and k not in {"city_choices", "branches_total"}
    }
    # Полный список филиалов города в промпт не кладём — только отобранные.
    if (
        "branches" in payload
        and isinstance(payload["branches"], list)
        and len(payload["branches"]) > 3
    ):
        payload["branches"] = payload["branches"][:3]
    if not payload:
        return ""
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    return (
        "Факты этого хода, которыми можно оперировать. Называть можно только "
        f"их; чего здесь нет — того не выдумывать:\n{body}"
    )


def dynamic_status_block(*, status: str, searching_retry: bool = False) -> str:
    """Инструкция генератору по статусу динамики контекста.

    ``DYN_MISSING`` — данных нет, вести разговор по известному.
    ``DYN_SEARCHING`` — данные готовятся. Статус один на весь контекст,
    и какой именно факт готовится, модель по нему не понимает: на прогоне
    цена лежала в статике, а бот отвечал «стоимость сейчас уточняю» и
    тянул время. Поэтому запрет привязан к тому, чего в разделах данных
    нет, а не ко всему разговору.
    ``DYN_READY`` и прочие — пустая строка.

    Args:
        status: ``dynamic_status`` из контекста.
        searching_retry: устаревший флаг; игнорируется.

    Returns:
        Текстовый блок или пустая строка.
    """
    del searching_retry
    if status == DYN_MISSING:
        return (
            "По нужному факту в данных ничего нет. Вслух об этом не сообщать, "
            "не извиняться и не объявлять о пробеле. Вести разговор дальше по "
            "тому, что известно — не выдумывать. Если по смыслу уместно — "
            "предложить прислать подробности в переписку, но только там, где "
            "разговор до мессенджера дошёл, а не посреди другой темы."
        )
    if status == DYN_SEARCHING:
        return (
            "По одному из фактов данные сейчас готовятся, и какой это факт — "
            "видно по разделам данных: чего в них нет, то и готовится. "
            "Выдумывать его нельзя ни в каком виде. Всё остальное, что в "
            "разделах уже есть, называется как обычно: готовящийся факт не "
            "делает недоступными цену, сроки и адреса, которые лежат рядом. "
            "Если всплыла именно та тема, по которой ждём, — обозначить это "
            "одной фразой и вести разговор дальше."
        )
    if status == DYN_READY:
        return ""
    return ""


def interrupted_reply_block(interrupted_reply: str | None) -> str:
    """Собирает раздел про обрыв предыдущей реплики бота.

    Пустое значение и ``None`` — реплика договорена, раздела нет.
    Раздел не предписывает договаривать: решение по смыслу разговора.

    Args:
        interrupted_reply: услышанная часть прерванной реплики.

    Returns:
        Текст раздела или пустая строка.
    """
    heard = (interrupted_reply or "").strip()
    if not heard:
        return ""
    return (
        "Предыдущая реплика была прервана: человек начал говорить, не дослушав.\n"
        f"Вот что он услышал:\n{heard}\n"
        "Остального он не слышал.\n"
        "Договаривать оборванное или нет — решать по разговору. "
        "Тема ещё нужна — довести мысль до конца, начиная с того места, "
        "где оборвалось. Человек своим вопросом или ответом уже снял тему — "
        "не возвращаться к ней. Правило доводить начатое до конца здесь "
        "само не решает: смотреть, снял ли человек тему своей репликой."
    )


def _history_without_interrupted_echo(
    history: Sequence[BaseMessage],
    interrupted_reply: str | None,
) -> list[BaseMessage]:
    """Убирает из хвоста истории услышанный кусок, если он уже в разделе обрыва.

    История в состоянии не меняется. В запрос к модели кусок не кладётся
    второй раз: в разделе обрыва он помечен как недоговорённый, а как
    обычная реплика бота выглядел бы законченным.

    Args:
        history: история звонка для промпта.
        interrupted_reply: услышанная часть прерванной реплики.

    Returns:
        Копия истории без последнего сообщения бота, совпадающего
        с услышанным куском или продолжающего его.
    """
    heard = (interrupted_reply or "").strip()
    if not heard:
        return list(history)
    messages = list(history)
    for index in range(len(messages) - 1, -1, -1):
        message = messages[index]
        if not isinstance(message, AIMessage):
            continue
        text = str(message.content or "").strip()
        if text == heard or text.startswith(heard):
            del messages[index]
            break
    return messages


def continuation_block(*, turn_kind: str) -> str:
    """Факт хода, на котором реплики человека не было.

    Ход запускается по паузе: человек молчит. Здесь только факт и ничего
    больше — никаких указаний, что говорить дальше. Что уместно сказать
    (уточнить, всё ли понятно, договорить обещанное, перейти к следующей
    теме), модель решает по разговору. Реплики-образцы сюда не добавлять:
    модель зачитывает их дословно в собственный ответ.

    Args:
        turn_kind: вид хода; блок нужен всем ходам без реплики человека —
            ``continuation``, ``silence`` и ``pull``.

    Returns:
        Текстовый блок или пустая строка для обычного хода по реплике человека.
    """
    if turn_kind not in {"continuation", "silence", "pull"}:
        return ""
    return "Реплики человека не было: он молчит, разговор продолжается."


def aside_block(script: CompiledScript, done: Sequence[str]) -> str:
    """Перечисляет возражения для `aside_id`.

    Справки в перечень не входят — их отдаёт контекстер в динамику контекста.

    Args:
        script: скомпилированный скрипт.
        done: уже отработанные возражения.

    Returns:
        Текстовый блок перечня возражений.
    """
    lines = ["Перечень возражений (для поля aside_id):"]
    for objection_id, item in script.objections.items():
        mark = " — уже отвечали" if objection_id in done else ""
        lines.append(f"- {objection_id}: возражение{mark}")
    lines.append("Ничего похожего в реплике нет — оставить aside_id пустым.")
    return "\n".join(lines)


def closed_steps_block(closed_steps: Sequence[AnyStep]) -> str:
    """Запрет пересказывать уже закрытые шаги.

    Args:
        closed_steps: шаги, закрытые к этому ходу.

    Returns:
        Текстовый блок или пустая строка.
    """
    if not closed_steps:
        return ""
    names: list[str] = []
    for step in closed_steps:
        name = getattr(step, "name", None) or getattr(step, "goal", None) or step.id
        names.append(str(name).strip() or step.id)
    listed = "; ".join(names)
    return (
        "Уже закрытые шаги (к их содержанию не возвращаться):\n"
        f"{listed}.\n"
        "То, что по ним уже сказано, повторять и пересказывать другими словами "
        "нельзя — человек это слышал. Ссылаться на сказанное коротко можно, "
        "разворачивать заново нельзя. "
        "Плохо: шаг про состав курса закрыт, а следующая реплика снова "
        "перечисляет, что входит в стоимость. "
        "Хорошо: коротко сослаться и идти дальше по текущему шагу."
    )


