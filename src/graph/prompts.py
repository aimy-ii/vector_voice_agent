def build_filler_messages(
    script: CompiledScript,
    *,
    messages: Sequence[BaseMessage],
    history_limit: int,
) -> list[BaseMessage]:
    """Собирает запрос на короткий отклик-заглушку, пока фон добывает данные.

    Не реплика, а знак «услышал» и пауза перед ответом. Промпт короткий —
    отклик должен родиться быстрее всего.

    Args:
        script: скомпилированный скрипт (нужна только персона).
        messages: история разговора.
        history_limit: сколько последних сообщений оставить.

    Returns:
        Список сообщений: одно системное и короткий хвост истории.
    """
    _ = script
    system = (
        f"{settings.agent_name}, к клиенту на «Вы», живой тон. "
        "Короткий отклик — не реплика: знак, что услышал, и взять паузу перед ответом. "
        "Ограничение длины: два-три слова, максимум одно короткое предложение. "
        "Не оценивать сказанное — никаких «замечательный выбор», "
        "«звучит основательно», «отличный город». "
        "Не рассуждать и не расспрашивать о чувствах, впечатлениях и ощущениях. "
        "Не задавать вопросов и не сообщать фактов. "
        "Не повторять то, что уже говорил в этом разговоре. "
        f"{_HARD_FACT_BAN}"
    )
    limit = max(1, int(history_limit))
    tail = list(messages)[-limit:]
    if not tail:
        tail = [HumanMessage(content="(клиент молчит)")]
    return [SystemMessage(content=system), *tail]


