#: Подмена одного правила для повторного захода на тему, когда собеседник
#: говорит. Полный режим ``repeat`` здесь не годится: он требует не уходить
#: с темы и обязательно вернуть ход, а человек в этот момент занят своим
#: вопросом — и бот переспрашивает одно и то же. Меняется только запрет
#: повтора; остальные правила штатные, врезки в раздел темы нет.
LEAD_REVISIT_OVERRIDES: dict[str, str] = {
    RULE_NO_VERBATIM: (
        "Свой вопрос по этой теме ты уже задавал, и ответа на него не было — "
        "человек говорит о своём. Задать его снова, в том числе другими "
        "словами, — ошибка: со стороны это переспрашивание одного и того же. "
        "Ответь на то, о чём человек спросил, и веди разговор дальше от его "
        "слов. К своей теме вернёшься, когда она придётся к месту."
    ),
}

#: Режимы сборки хода. ``normal`` — штатный промпт; ``repeat`` — повторный заход
#: по одной теме; ``pull`` — вытаскивание, когда человек молчит после двух реплик
#: бота подряд и задача хода — вывести его на слово; ``revisit`` — повторный
#: заход на тему, когда собеседник говорит: меняется только запрет повтора.
TurnMode = Literal["normal", "repeat", "pull", "revisit"]


def speech_rules_block(*, mode: TurnMode = "normal") -> str:
    """Собирает нумерованный список правил речи.

    Последним пунктом во всех режимах идёт жёсткий запрет называть факты
    вне переданных данных (``_HARD_FACT_BAN``).

    Args:
        mode: режим сборки хода. При ``repeat`` часть правил берётся из
            ``LEAD_REPEAT_OVERRIDES``. При ``pull`` — из
            ``LEAD_PULL_OVERRIDES``. При ``revisit`` подменяется одно
            правило из ``LEAD_REVISIT_OVERRIDES``. При ``normal`` список
            штатный, символ в символ, плюс последний пункт-запрет.

    Returns:
        Правила речи одной строкой, по одному правилу на строку.
    """
    rules = SPEECH_RULES
    if mode == "repeat":
        rules = tuple(LEAD_REPEAT_OVERRIDES.get(rule, rule) for rule in rules)
    elif mode == "pull":
        rules = tuple(LEAD_PULL_OVERRIDES.get(rule, rule) for rule in rules)
    elif mode == "revisit":
        rules = tuple(LEAD_REVISIT_OVERRIDES.get(rule, rule) for rule in rules)
    numbered = [f"{index}. {rule}" for index, rule in enumerate(rules)]
    numbered.append(f"{len(rules)}. {_HARD_FACT_BAN}")
    return "\n".join(numbered)


def profile_block(
    script: CompiledScript,
    profile: Mapping[str, str],
    *,
    pending_fields: Sequence[str] = (),
) -> str:
    """Показывает форму профиля в трёх состояниях.

    Секции: что известно, что уточняется прямо сейчас, чего ещё не знаем.
    Поле из ``pending_fields`` попадает во вторую секцию, даже если значение
    пустое, и не дублируется в третьей. В формате продаж перечень полей не
    объявлен — секции «чего не знаем» нет, а «уточняется» будет.

    Args:
        script: скомпилированный скрипт.
        profile: собранный профиль.
        pending_fields: поля, которые лайв-канал сейчас разбирает.

    Returns:
        Текстовый блок для системного сообщения.
    """
    pending = {str(key).strip() for key in pending_fields if str(key).strip()}
    known: list[str] = []
    clarifying: list[str] = []
    unknown: list[str] = []

    def _label(key: str, field: Any = None) -> str:
        if field is None:
            return key
        whose = "звонящий" if field.role == "caller" else "будущий курсант"
        return f"{key} ({field.title}, {whose})"

    if script.is_sales:
        for key, raw_value in sorted(profile.items()):
            raw = str(raw_value).strip()
            if key in pending:
                value = given_name(raw) if key in {"caller_name", "student_name"} and raw else raw
                line = f"- {key}: {value}" if value else f"- {key}"
                clarifying.append(line)
                continue
            if not raw:
                continue
            value = given_name(raw) if key in {"caller_name", "student_name"} else raw
            known.append(f"- {key}: {value}")
        for key in sorted(pending):
            if any(line.startswith(f"- {key}") for line in clarifying):
                continue
            clarifying.append(f"- {key}")
        parts = ["Что уже известно:"]
        parts.append("\n".join(known) if known else "- пока ничего")
        if clarifying:
            parts.append(
                "\nЧто уточняется прямо сейчас (поле разбирается — "
                "переспрашивать не надо, скоро будет известно):"
            )
            parts.append("\n".join(clarifying))
        return "\n".join(parts)

    for key, field in script.profile_fields.items():
        raw = str(profile.get(key, "")).strip()
        value = given_name(raw) if key in {"caller_name", "student_name"} and raw else raw
        label = _label(key, field)
        if key in pending:
            line = f"- {label}: {value}" if value else f"- {label}"
            clarifying.append(line)
        elif value:
            known.append(f"- {label}: {value}")
        else:
            unknown.append(f"- {label}")

    for key in sorted(pending):
        if key in script.profile_fields:
            continue
        if any(line.startswith(f"- {key}") for line in clarifying):
            continue
        clarifying.append(f"- {key}")

    parts = ["Что уже известно:"]
    parts.append("\n".join(known) if known else "- пока ничего")
    if clarifying:
        parts.append(
            "\nЧто уточняется прямо сейчас (поле разбирается — "
            "переспрашивать не надо, скоро будет известно):"
        )
        parts.append("\n".join(clarifying))
    if unknown:
        parts.append("\nЧего ещё не знаем (переспрашивать известное — ошибка):")
        parts.append("\n".join(unknown))
    return "\n".join(parts)


