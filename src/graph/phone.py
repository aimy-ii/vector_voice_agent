"""Телефонный номер из речи: принимаем только то, что похоже на номер.

Агент профиля возвращает значения полей словами клиента, и для большинства
полей это правильно: «механика», «вечером после семи» — так и надо
записать. Для номера так нельзя. На разборе живого звонка человек сказал
«мне удобнее в Телеграме на том же номере, что и телефон для связи», и в
поле ``caller_phone`` легла эта самая фраза. Поле структурное: из него
звонят и пишут, и текст вместо цифр там хуже пустоты — пустое видно, а
фраза выглядит заполненным полем.

По той же причине проверяется и длина. Распознавание теряет цифры, когда
человек диктует номер: «пятьсот пятьдесят пять ноль один двадцать три»
приходит как «55-01-23». В двадцати трёх прогонах из двадцати пяти в
анкете лежало десять цифр вместо одиннадцати — по такому номеру не
перезвонить, а поле выглядит заполненным. Недобранный номер отбрасываем:
поле остаётся пустым, шаг — открытым, и бот спрашивает номер снова.
"""

from __future__ import annotations

import re

#: Длина российского номера с кодом страны.
RU_FULL_DIGITS = 11

#: Длина российского мобильного, названного без кода страны.
RU_SHORT_DIGITS = 10

#: Цифры, с которых начинается российский номер с кодом страны.
RU_COUNTRY_HEADS = ("7", "8")

#: Цифра, с которой начинается российский мобильный без кода страны.
RU_MOBILE_HEAD = "9"

#: Потолок: длиннее международного номера не бывает (E.164 — пятнадцать).
#: Более длинная цепочка — это слипшиеся числа, а не номер.
MAX_DIGITS = 15

_DIGITS = re.compile(r"\d")


def phone_number(value: str) -> str:
    """Возвращает номер, если он есть в сказанном, иначе пустую строку.

    Формулировку человека не переписываем: записываем как сказал, но
    только когда набор цифр складывается в номер целиком.

    Российский номер — одиннадцать цифр с кодом страны либо десять, если
    человек назвал мобильный без кода. Иностранный номер кодом страны
    начинаться не может, поэтому для него проверяется только длина.
    Всё остальное — недобор: на фразе с числами («после семи», «мне
    двадцать девять») цифр не хватит, а на потерянной распознаванием
    цифре номер окажется на единицу короче.

    Args:
        value: значение поля так, как его вернул агент профиля.

    Returns:
        Исходная строка без крайних пробелов либо пустая строка, если
        номера в ней нет.

    Examples:
        «+7 921 555-01-23» — без изменений;
        «+7 921 550123» → пустая строка, цифры не хватает;
        «восемь девятьсот двадцать один» → пустая строка;
        «тот же номер, что и телефон для связи» → пустая строка.
    """
    text = (value or "").strip()
    if not text:
        return ""
    digits = "".join(_DIGITS.findall(text))
    if not digits or len(digits) > MAX_DIGITS:
        return ""
    if digits[0] in RU_COUNTRY_HEADS:
        return text if len(digits) == RU_FULL_DIGITS else ""
    if len(digits) == RU_SHORT_DIGITS:
        return text if digits[0] == RU_MOBILE_HEAD else ""
    return text if len(digits) > RU_SHORT_DIGITS else ""
