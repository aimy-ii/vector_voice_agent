"""Поля анкеты со своей формой: филиал и формат теории.

Агент профиля возвращает значение словами человека. Для большинства полей
это верно, но у некоторых форма задана заранее, и свободный текст в них
хуже пустоты — из анкеты работают дальше, а не читают её глазами.

На прогонах в поле выбранного филиала ложилось «Нурамыше» (распознавание
переврало «на Уралмаше») и «Метро Проспект Космонавтов» — ориентир вместо
адреса. В формате теории — «Дома», «Очно дома», «В теории лучше очно дома
отвлекается» вместо одного из трёх вариантов.
"""

from __future__ import annotations

import re

#: Варианты формата теории, как они объявлены в скрипте.
THEORY_FORMATS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Комбинированно", ("комбинир", "и так и так", "совмещ")),
    ("Дистанционно", ("дистанцион", "онлайн", "в приложении", "удалён", "удален", "дома")),
    ("Очно", ("очно", "в классе", "в школе", "офлайн", "лично", "приезжать")),
)

_DIGIT = re.compile(r"\d")


def theory_format(value: str) -> str:
    """Сводит сказанное к одному из вариантов формата теории.

    Порядок проверки важен: «очно дома» человек говорит про очные занятия
    рядом с домом, а «дома» без «очно» — про дистанционные. Поэтому очный
    вариант проверяется последним и перебивает остальные.

    Args:
        value: значение поля так, как его вернул агент профиля.

    Returns:
        Один из вариантов либо пустая строка, если ни один не узнан.

    Examples:
        «Теорию хочет— очно» → «Очно»;
        «Дома» → «Дистанционно»;
        «В теории лучше очно дома отвлекается» → «Очно».
    """
    text = (value or "").lower().replace("ё", "е")
    if not text.strip():
        return ""
    found = ""
    for name, markers in THEORY_FORMATS:
        if any(marker.replace("ё", "е") in text for marker in markers):
            found = name
    return found


def branch_address(value: str) -> str:
    """Возвращает адрес филиала, если это адрес, иначе пустую строку.

    Адрес филиала всегда с номером дома: «Восстания, 21», «Коломяжский
    проспект, 15, корпус 2». Ориентир номера не имеет — «Уралмаш», «метро
    Проспект Космонавтов», — и филиалом не является: по нему филиал ещё
    только подбирают, и он уже лежит в своём поле.

    Args:
        value: значение поля так, как его вернул агент профиля.

    Returns:
        Исходная строка без крайних пробелов либо пустая строка.
    """
    text = (value or "").strip()
    if not text or not _DIGIT.search(text):
        return ""
    return text
