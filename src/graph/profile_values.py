"""Филиал в анкете: адрес справочника, а не пересказ клиента.

Агент профиля возвращает значение словами человека. Для большинства полей
это верно, но филиал — значение из справочника: клиент говорит «Восстание
двадцать один», а в анкете должно стоять «улица Восстания, дом 21» — то
же место, но одной записью от звонка к звонку.

На прогонах в это поле ложилось «Нурамыше» (распознавание переврало «на
Уралмаше») и «Метро Проспект Космонавтов» — ориентир вместо адреса. По
ориентиру филиал ещё только подбирают, и лежит он в своём поле.

Поля, у которых форма задана перечнем вариантов, разбирает
``script.field_choices``: варианты там данные, а не код.
"""

from __future__ import annotations

import re
from typing import Sequence

_DIGIT = re.compile(r"\d")
_WORD = re.compile(r"[а-яa-z]+", re.IGNORECASE)
_NUMBER = re.compile(r"\d+")

#: Слова адреса, общие для всех филиалов: по ним места не различить.
_ADDRESS_WORDS = frozenset(
    {
        "улица",
        "ул",
        "дом",
        "д",
        "корпус",
        "корп",
        "к",
        "строение",
        "стр",
        "проспект",
        "пр",
        "просп",
        "переулок",
        "пер",
        "шоссе",
        "ш",
        "площадь",
        "пл",
        "бульвар",
        "б",
        "набережная",
        "наб",
        "метро",
        "станция",
        "район",
    }
)

#: Сколько первых букв слова сравнивать.
#:
#: Падежи в речи и в справочнике разные: «Восстание» против «Восстания»,
#: «Кузнецова» против «Кузнецов». Основы у них общие, окончания — нет.
STEM = 5


def _stems(text: str) -> frozenset[str]:
    """Основы значащих слов адреса.

    Args:
        text: адрес или то, что назвал человек.

    Returns:
        Основы слов, по которым места различаются.
    """
    words = _WORD.findall((text or "").lower().replace("ё", "е"))
    return frozenset(w[:STEM] for w in words if w not in _ADDRESS_WORDS)


def _numbers(text: str) -> frozenset[str]:
    """Числа адреса: номер дома, корпуса, строения."""
    return frozenset(_NUMBER.findall(text or ""))


def _same_place(spoken: str, address: str) -> bool:
    """Одно ли место названо.

    Числа названного должны найтись в адресе — иначе это соседний дом, —
    и хотя бы одна основа должна совпасть, иначе это другая улица.

    Args:
        spoken: как человек назвал место.
        address: адрес филиала из справочника.

    Returns:
        ``True``, если это один и тот же филиал.
    """
    if not (_stems(spoken) & _stems(address)):
        return False
    return _numbers(spoken) <= _numbers(address)


def branch_address(value: str, known: Sequence[str] = ()) -> str:
    """Возвращает филиал адресом справочника либо пустую строку.

    Филиал — значение из справочника, а не из речи: в анкете он должен
    выглядеть одинаково от звонка к звонку. Поэтому названное сверяется с
    адресами филиалов, которые бот предлагал, и записывается адрес
    карточки: «Восстание двадцать один» → «улица Восстания, дом 21».

    Улица знакомая, а номер дома другой — значит номер переврали: своего
    филиала по такому адресу нет, и записывать его нельзя.

    Если карточек нет под рукой или речь о вовсе другой улице, остаётся
    прежняя примета: адрес филиала всегда с номером дома. Ориентир номера
    не имеет — «Уралмаш», «метро Проспект Космонавтов», — и филиалом не
    является: по нему филиал ещё только подбирают, и он уже лежит в своём
    поле.

    Args:
        value: значение поля так, как его вернул агент профиля.
        known: адреса филиалов, известные по ходу разговора.

    Returns:
        Адрес филиала либо пустая строка.
    """
    text = (value or "").strip()
    if not text:
        return ""
    matched = [address for address in known if address and _same_place(text, address)]
    if len(matched) == 1:
        return matched[0]
    if len(matched) > 1:
        # Несколько филиалов на одной улице: гадать, какой из них назвали,
        # хуже, чем оставить поле пустым и спросить ещё раз.
        return ""
    if any(address and (_stems(text) & _stems(address)) for address in known):
        return ""
    return text if _DIGIT.search(text) else ""
