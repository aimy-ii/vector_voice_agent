"""Схема вызова генератора за ход.

Чекер закрывает шаги отдельно. Профиль разбирает лайв-канал. Генератор
пишет реплику и признак прощания. ``reply`` объявлен первым — реплика
начинает генерироваться сразу; булево поле завершения — последним, чтобы
не задерживать первый токен.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class TurnResult(BaseModel):
    """Ответная реплика генератора — за один вызов."""

    reply: str = Field(
        default="",
        description=(
            "Что бот говорит вслух. Одна-две короткие фразы, разговорный русский, "
            "без списков, без разметки, без цифр в скобках."
        ),
    )
    conversation_ended: bool = Field(
        default=False,
        description=(
            "True только когда разговор действительно окончен: стороны "
            "попрощались, у собеседника не осталось вопросов и в разговоре "
            "больше нет незавершённого дела. Прощание в середине разговора, "
            "вежливое «спасибо» или пауза признаком завершения не являются."
        ),
    )


#: Имя схемы для провайдера.
TURN_SCHEMA_NAME = "vector_turn"
