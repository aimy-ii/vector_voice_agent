"""Схема вызова генератора за ход.

Чекер закрывает шаги отдельно. Профиль разбирает лайв-канал. Генератор
пишет реплику и служебные поля возражения. ``reply`` объявлен первым —
реплика начинает генерироваться сразу.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class TurnResult(BaseModel):
    """Ответная реплика и служебные поля возражения — за один вызов генератора."""

    reply: str = Field(
        default="",
        description=(
            "Что бот говорит вслух. Одна-две короткие фразы, разговорный русский, "
            "без списков, без разметки, без цифр в скобках."
        ),
    )
    aside_id: str | None = Field(
        default=None,
        description=(
            "Идентификатор возражения из переданного перечня, если клиент "
            "возразил («подумаю», «дорого», «сравниваю»). Справки сюда не "
            "относятся — их текст уже в контексте. Иначе пусто."
        ),
    )
    resume_step: bool = Field(
        default=True,
        description=(
            "Возвращаться ли к текущему шагу сразу в этой же реплике после "
            "ответа на возражение. False — только если возврат прозвучит неуместно."
        ),
    )


#: Имя схемы для провайдера.
TURN_SCHEMA_NAME = "vector_turn"
