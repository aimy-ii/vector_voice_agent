"""Схема вызова генератора за ход.

Чекер закрывает шаги отдельно. Профиль разбирает лайв-канал. Генератор
пишет реплику и признак прощания. ``reply`` объявлен первым — реплика
начинает генерироваться сразу; булево поле завершения — последним, чтобы
не задерживать первый токен.
"""

from __future__ import annotations

from pydantic import BaseModel, Field


class TurnResult(BaseModel):
    """Ответная реплика генератора — за один вызов."""

    reply: str = Field(
        default="",
        description=(
            "Что бот говорит вслух. Одна-две короткие фразы, разговорный русский, "
            "без списков, без разметки, без цифр в скобках."
        ),
    )
    conversation_ended: bool = Field(
        default=False,
        description=(
            "True только если в последней реплике собеседника прозвучало "
            "прощание: «до свидания», «всего доброго», «спасибо, до связи», "
            "«мне пора» и тому подобное. Смотреть надо именно слова человека, "
            "а не свои. Собственная прощальная фраза агента признаком не "
            "является: агент может попрощаться первым, а признак ставится "
            "следующим ходом, когда человек ответил прощанием. "
            "Договорённость о встрече, запись, обещание прислать документы, "
            "фраза «если появятся вопросы — пишите» завершением не являются. "
            "Сомневаешься — не ставить: лишний ход дешевле, чем брошенная трубка."
        ),
    )


#: Имя схемы для провайдера.
TURN_SCHEMA_NAME = "vector_turn"
