"""Схема единственного вызова модели за ход.

Оценка едет вместе с генерацией: разобранный ответ клиента, статус шага и
текст реплики возвращаются одним вызовом. Второй заход к модели — это лишняя
секунда молчания в трубке, поэтому его нет.

Два правила формы, оба про задержку:

* **Полей мало и они короткие.** Ни одного поля вида «поясни своё решение»:
  лишнее поле — лишние токены — молчание в трубке.
* **`reply` объявлен последним.** Служебные поля занимают несколько десятков
  токенов и приходят почти мгновенно, зато к моменту генерации реплики модель
  уже определилась с разбором. Обратный порядок дал бы реплику, написанную
  вслепую.

Ответ клиента и посторонний вопрос — **два независимых поля**. «Механика.
А сколько стоит?» это одновременно ответ на шаг и справка о цене; поле
«тип реплики» потеряло бы одно из двух.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field


class ProfileValue(BaseModel):
    """Распознанное значение поля профиля.

    Список пар, а не словарь: словарь со свободными ключами разные
    OpenAI-совместимые провайдеры описывают в схеме по-разному, а список пар
    понимают одинаково.
    """

    key: str = Field(description="Ключ поля профиля из переданного перечня.")
    value: str = Field(description="Значение так, как его назвал клиент.")


class TurnResult(BaseModel):
    """Разбор реплики клиента и ответная реплика — за один вызов."""

    understood: list[ProfileValue] = Field(
        default_factory=list,
        description=(
            "Что удалось понять из последней реплики клиента. Только поля из "
            "переданного перечня и только то, что клиент действительно сказал. "
            "Ничего не додумывать."
        ),
    )
    step_status: Literal["done", "refused", "unclear"] = Field(
        default="unclear",
        description=(
            "Ответил ли клиент на текущий шаг: done — ответил; refused — "
            "уклонился или отказался отвечать; unclear — ответа на шаг в реплике нет."
        ),
    )
    aside_id: str | None = Field(
        default=None,
        description=(
            "Идентификатор справки или возражения из переданного перечня, если "
            "клиент задал посторонний вопрос или возразил. Иначе пусто."
        ),
    )
    resume_step: bool = Field(
        default=True,
        description=(
            "Возвращаться ли к текущему шагу сразу в этой же реплике после "
            "ответа на посторонний вопрос. False — только если возврат прозвучит неуместно."
        ),
    )
    reply: str = Field(
        default="",
        description=(
            "Что бот говорит вслух. Одна-две короткие фразы, разговорный русский, "
            "без списков, без разметки, без цифр в скобках."
        ),
    )


#: Имя схемы для провайдера.
TURN_SCHEMA_NAME = "vector_turn"
